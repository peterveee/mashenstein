// songs. 2 Oct 2026.
//
// Shared by tools/banger-levels.js (`refs`, `check`) and tools/lib/banger-seeds.js (Use as
// Style, Save as Combo). What a reference is, and why, is at the top of
// tools/lib/banger/levels.js: the part a channel's settings were set for, with that
// channel's fader and widener — a seed remix's channel, a seed banger's, a combo's, or the
// style's own default part where nobody has set it by ear.

// Read and rewrite the machine-owned Song Mixer effect preset module.
//
// Unlike the hand-authored voice catalogue, this file is intentionally a complete
// data export. Re-emitting it keeps the write path small and makes the update atomic;
// the `presets` objects are carried through unchanged for the future named-preset UI.
import { readFileSync, writeFileSync, renameSync, rmSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
export const EFFECT_PRESETS_PATH = join(ROOT, 'src/data/effect-presets.js');

let importSeq = 0;

export async function readEffectPresets(path = EFFECT_PRESETS_PATH) {
  const url = `${pathToFileURL(path).href}?effectPresetVersion=${++importSeq}`;
  const mod = await import(url);
  return mod.EFFECT_PRESETS || { inserts: {}, returns: {} };
}

export function renderEffectPresets(value) {
  return '// Generated by the Song Mixer DEV effect-default writer.\n'
    + '// Keep this file as source data; named presets can be added under `presets`.\n'
    + `export const EFFECT_PRESETS = ${JSON.stringify(value, null, 2)};\n`;
}

/** Keep only the current catalogue keys, filling additions from code defaults. */
export function normalizeKnownDefaults(params, keys, fallback) {
  const input = params && typeof params === 'object' && !Array.isArray(params) ? params : {};
  const out = {};
  for (const key of keys) {
    const value = Object.prototype.hasOwnProperty.call(input, key) ? input[key] : fallback?.[key];
    if (value === undefined) throw new Error(`missing fallback for "${key}"`);
    out[key] = value;
  }
  return out;
}

/** Rewrite only after the candidate has successfully parsed as an ES module. */
export async function writeEffectPresetsAtomic(value, path = EFFECT_PRESETS_PATH) {
  const tmp = `${path}.tmp-${process.pid}-${Date.now()}.js`;
  const source = renderEffectPresets(value);
  writeFileSync(tmp, source, 'utf8');
  try {
    await readEffectPresets(tmp);
    renameSync(tmp, path);
  } catch (err) {
    rmSync(tmp, { force: true });
    throw err;
  }
  return source;
}

export function readEffectPresetsSource(path = EFFECT_PRESETS_PATH) {
  return readFileSync(path, 'utf8');
}

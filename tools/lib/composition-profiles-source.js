// src/data/composition-profiles.js as source — the writer, the snapshot.
//
// The same shape as stage-layouts-source.js, and for the same reason: the
// tuner's server and the tests must format and judge the file with one piece
// of code, or the first hand-tidied diff becomes a phantom change.
//
// ONE EMIT RULE, and it is the optional one: a cabinet writes only the bands
// it actually moves, and a stage writes only what it changes from its
// cabinet. Everything else resolves from the defaults in scenery-layout.js.
// This file is read by people deciding what a cabinet claims, so a cabinet
// that claims nothing must look like it.
import { readFileSync, writeFileSync, renameSync, mkdirSync, existsSync, readdirSync, unlinkSync, copyFileSync } from 'node:fs';
import { join } from 'node:path';
import { SCENERY_BANDS } from '../../src/engine/scenery-layout.js';
import { PORTRAIT_GROUND_ANCHOR_RATIO } from '../../src/engine/portrait-geometry.js';
import { COMPOSITION_BAND_NAMES, validateCompositionProfile } from '../../src/engine/composition-profile.js';

const REL = 'src/data/composition-profiles.js';
const HISTORY_DIR = 'work/composition-history';
const HISTORY_CAP = 300;

// Two decimals is the tuner's drag snap; the ground ratio gets three because
// its own clamp works in 0.005 steps.
const fmtBand = (pair) => `[${pair[0].toFixed(2)}, ${pair[1].toFixed(2)}]`;
const near = (a, b) => Math.abs(a - b) < 1e-9;
const sameBand = (a, b) => Array.isArray(a) && Array.isArray(b)
  && near(a[0], b[0]) && near(a[1], b[1]);

const HEADER = `// GENERATED by tools/composition-tuner.js. Do not edit by hand.
//
// Authored portrait composition per cabinet: where each scenery band sits in
// the scenery rectangle, and where the resting groundline sits in the safe
// frame. Everything omitted resolves from the defaults in
// src/engine/scenery-layout.js — a cabinet listed with no bands is a cabinet
// that composes exactly like the default profile.
//
// Numbers are normalized (0..1) to the scenery rectangle, so they mean the
// same composition on every supported phone. Run \`npm run composition\` to
// change them: dragging the bands on a real level is the only way to judge
// them, and the tuner is what writes this file.
`;

/**
 * The bands and ratio a layer actually changes, relative to the layer under
 * it. Returns null when it changes nothing, so the caller can drop the entry.
 */
function diffProfile(profile, base) {
  const bands = {};
  for (const name of COMPOSITION_BAND_NAMES) {
    const band = profile?.bands?.[name];
    if (!band) continue;
    if (sameBand(band, base.bands[name])) continue;
    bands[name] = band;
  }
  const ratio = Number(profile?.groundAnchorRatio);
  const movedRatio = Number.isFinite(ratio) && !near(ratio, base.groundAnchorRatio);
  if (!Object.keys(bands).length && !movedRatio) return null;
  return { bands, groundAnchorRatio: movedRatio ? ratio : null };
}

function bandsSource(bands, indent) {
  const pad = ' '.repeat(indent);
  const rows = COMPOSITION_BAND_NAMES
    .filter((name) => bands[name])
    .map((name) => `${pad}  ${name}: ${fmtBand(bands[name])},`);
  return `{\n${rows.join('\n')}\n${pad}}`;
}

function entrySource(id, entry, indent) {
  const pad = ' '.repeat(indent);
  const parts = [];
  if (entry.diff) {
    if (entry.diff.groundAnchorRatio != null) {
      parts.push(`${pad}  groundAnchorRatio: ${entry.diff.groundAnchorRatio.toFixed(3)},`);
    }
    if (Object.keys(entry.diff.bands).length) {
      parts.push(`${pad}  bands: ${bandsSource(entry.diff.bands, indent + 2)},`);
    }
  }
  const stageIds = Object.keys(entry.stages || {}).sort();
  if (stageIds.length) {
    const rows = stageIds.map((stageId) => {
      const stage = entry.stages[stageId];
      const inner = [];
      if (stage.groundAnchorRatio != null) {
        inner.push(`${pad}      groundAnchorRatio: ${stage.groundAnchorRatio.toFixed(3)},`);
      }
      if (Object.keys(stage.bands).length) {
        inner.push(`${pad}      bands: ${bandsSource(stage.bands, indent + 6)},`);
      }
      return `${pad}    '${stageId}': {\n${inner.join('\n')}\n${pad}    },`;
    });
    parts.push(`${pad}  stages: {\n${rows.join('\n')}\n${pad}  },`);
  }
  if (!parts.length) return `${pad}${id}: {},`;
  return `${pad}${id}: {\n${parts.join('\n')}\n${pad}},`;
}

/**
 * Render the whole file. `profiles` is { cabinetId: { bands, groundAnchorRatio,
 * stages: { stageId: { bands, groundAnchorRatio } } } } holding FULL resolved
 * values; the diffing against the defaults happens here.
 */
export function renderCompositionProfiles(profiles) {
  const base = { bands: SCENERY_BANDS, groundAnchorRatio: PORTRAIT_GROUND_ANCHOR_RATIO };
  const ids = Object.keys(profiles || {}).sort();
  const entries = ids.map((id) => {
    const raw = profiles[id] || {};
    const cabinet = validateCompositionProfile(raw, base);
    const diff = diffProfile(cabinet, base);
    const stages = {};
    for (const [stageId, stageRaw] of Object.entries(raw.stages || {})) {
      const stage = validateCompositionProfile(stageRaw, cabinet);
      const stageDiff = diffProfile(stage, cabinet);
      if (stageDiff) stages[stageId] = stageDiff;
    }
    return { id, diff, stages };
  }).filter((entry) => entry.diff || Object.keys(entry.stages).length);
  const body = entries.length
    ? entries.map((entry) => entrySource(entry.id, entry, 2)).join('\n')
    : '';
  return `${HEADER}export const COMPOSITION_PROFILES = {${body ? `\n${body}\n` : ''}};\n`;
}

/**
 * Write the file if it changed. Atomic (tmp + rename) so a crashed save never
 * leaves a half-written module where the game expects data.
 */
export function writeCompositionProfiles(root, profiles) {
  const out = join(root, REL);
  const next = renderCompositionProfiles(profiles);
  if (existsSync(out) && readFileSync(out, 'utf8') === next) return false;
  mkdirSync(join(root, 'src/data'), { recursive: true });
  const tmp = `${out}.tmp`;
  writeFileSync(tmp, next);
  renameSync(tmp, out);
  return true;
}

export function snapshotCompositionProfiles(root) {
  const src = join(root, REL);
  if (!existsSync(src)) return null;
  const dir = join(root, HISTORY_DIR);
  mkdirSync(dir, { recursive: true });
  const stamp = new Date().toISOString().replace(/[:.]/g, '-').slice(0, 19);
  const dest = join(dir, `composition-profiles-${stamp}.js`);
  copyFileSync(src, dest);
  const all = readdirSync(dir).filter((f) => f.startsWith('composition-profiles-')).sort();
  for (const f of all.slice(0, Math.max(0, all.length - HISTORY_CAP))) unlinkSync(join(dir, f));
  return dest;
}

export const COMPOSITION_PROFILES_REL = REL;

// WHEN EVERY CUE IN THE GAME WAS BORN — derived from git, written down once,
// and kept honest by a test from here on.
//
// Peter asked how old each sound is. Nothing in the engine records it, but the
// repository does: a cue is a `case 'name':` in the sfx switch, so the commit
// that first introduced that string is the day the sound started existing.
// `git log -S` finds exactly that — the commit where the number of occurrences
// of the string changed from zero — and `--follow` carries it back through any
// rename of audio.js itself.
//
// WHAT THIS CAN AND CANNOT KNOW:
//
//   * A cue that was RENAMED reads as born on the rename. The sound may be
//     older; the name is not. (The switch that became `switchFlick` is the live
//     example: the block cue's first pass was called nothing of the kind.)
//   * A cue whose recipe was rewritten keeps its original date. That is the
//     intent — this is when the cue entered the game, not when it last changed.
//   * A cue that lived in another module before audio.js existed reads as born
//     when it arrived here. The fallback below widens the search to the whole
//     tree before giving up, which catches most of those.
//
// Usage:  node tools/sfx-birthdays.js          rewrite src/data/sfx-birthdays.js
//         node tools/sfx-birthdays.js --check  list cues with no recorded date
//
// The generated file is TRACKED, and deliberately: a date nobody commits is a
// date the next clone recomputes from a history that has since been rewritten,
// and the whole point is that the answer stops moving. New cues are added to it
// by running this; tests/sfx-desk-coverage.js fails until one is.
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const AUDIO = 'src/engine/audio.js';
const OUT = join(root, 'src/data/sfx-birthdays.js');

const git = (args) => {
  try {
    return execFileSync('git', args, { cwd: root, encoding: 'utf8' }).trim();
  } catch {
    return '';
  }
};

export function cueNames(source = readFileSync(join(root, AUDIO), 'utf8')) {
  const start = source.indexOf('switch (name)');
  if (start < 0) return [];
  // The switch's own body: up to the closing brace at method indentation.
  const body = source.slice(start, source.indexOf('\n  }', start));
  return [...new Set([...body.matchAll(/case '([A-Za-z0-9_]+)':/g)].map((m) => m[1]))].sort();
}

function birthday(cue) {
  // The commit that took this string from absent to present, oldest first.
  const inAudio = git(['log', '-S', `case '${cue}':`, '--reverse', '--follow',
    '--format=%ad|%h', '--date=short', '--', AUDIO]).split('\n')[0];
  if (inAudio) return inAudio.split('|');
  // Older than this file, or it moved: ask the whole tree for the name itself.
  const anywhere = git(['log', '-S', `'${cue}'`, '--reverse',
    '--format=%ad|%h', '--date=short', '--', 'src']).split('\n')[0];
  return anywhere ? anywhere.split('|') : [null, null];
}

const cues = cueNames();
const rows = cues.map((cue) => {
  const [date, commit] = birthday(cue);
  return { cue, date, commit };
});

if (process.argv.includes('--check')) {
  const unknown = rows.filter((r) => !r.date);
  console.log(`${rows.length} cues, ${rows.length - unknown.length} dated`);
  if (unknown.length) console.log('no date found:', unknown.map((r) => r.cue).join(' '));
  process.exit(0);
}

const byDate = [...rows].sort((a, b) => String(a.date).localeCompare(String(b.date)) || a.cue.localeCompare(b.cue));
const first = byDate.find((r) => r.date)?.date;
const body = byDate
  .map((r) => `  ${r.cue}: ${r.date ? `'${r.date}'` : 'null'},${r.commit ? `   // ${r.commit}` : ''}`)
  .join('\n');

writeFileSync(OUT, `// WHEN EVERY SFX CUE WAS BORN — generated by tools/sfx-birthdays.js.
//
// The day the cue's name first appeared in the repository, which is the day the
// sound started existing. Oldest first, so the file reads as the order the game
// learned to make noise: ${first} is the day audio.js landed, and everything
// dated that day is day one.
//
// A cue renamed since reads as born on the rename, and a cue whose recipe was
// rewritten keeps its original date — this records when it ENTERED the game,
// not when it last changed. The tool's header has the full caveats.
//
// Regenerate with \`node tools/sfx-birthdays.js\`; a new cue with no entry here
// fails tests/sfx-desk-coverage.js, which is what keeps the record complete.
export const SFX_BIRTHDAYS = {
${body}
};

export function sfxBorn(cue) { return SFX_BIRTHDAYS[cue] || null; }
`);
console.log(`wrote ${rows.length} cue dates to src/data/sfx-birthdays.js`);
const undated = rows.filter((r) => !r.date);
if (undated.length) console.log('undated:', undated.map((r) => r.cue).join(' '));

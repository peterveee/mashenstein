// Compile the C DSP cores under src/engine/mrdr3wasm/ to WebAssembly.
//
//   node tools/build-wasm.js
//
// docs/WASM-audio-engine-plan.md §2. Freestanding C — no Emscripten, no JS glue — through
// Homebrew's LLVM (see tools/lib/wasm-cores.js for the toolchain and why each piece).
//
// Each core's bytes are written as base64 into a TRACKED module beside its source
// (`<name>.wasm.js`), the way tngr2/generated-tables.js is tracked: the game builds
// without LLVM installed, and only this Mac ever needs the toolchain. The module carries a
// hash of the source and flags; tests/wasm-worklet-proof.js fails if they go stale.
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { compileWasm, wasmSourceHash, wasmToolchainMissing, WASM_CORES } from './lib/wasm-cores.js';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');

const missing = wasmToolchainMissing();
if (missing) {
  console.error(`No wasm toolchain (${missing}).\n  brew install llvm lld wasi-libc`);
  process.exit(1);
}

for (const core of WASM_CORES) {
  const src = join(ROOT, core.source);
  const bytes = compileWasm(src);
  const hash = wasmSourceHash(readFileSync(src, 'utf8'));
  const upper = core.name.toUpperCase();
  writeFileSync(join(ROOT, core.output), [
    `// GENERATED by tools/build-wasm.js from ${core.source.split('/').pop()} — do not edit.`,
    '// Rebuild with `node tools/build-wasm.js` (needs `brew install llvm lld wasi-libc`).',
    `export const ${upper}_WASM_SOURCE_HASH = '${hash}';`,
    `export const ${upper}_WASM_BASE64 = '${bytes.toString('base64')}';`,
    '',
  ].join('\n'));
  console.log(`${core.name}: ${bytes.length} bytes -> ${core.output}`);
}

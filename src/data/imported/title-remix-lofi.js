// EMPTY ARCADE — LOFI — one song: what it plays, how it is arranged, how it sounds.
//
// EMPTY ARCADE as a chillhop / lo-fi hip-hop beat — a game alternate of title, on the desk and
// the dev menu. Nothing replaces title.js: the title screen and the opening film play it directly.
// 
// Peter: "some groovy new remixes for the ... title music". LOFI: Nujabes, J Dilla's lazy swing,
// the 2010s study-beats tape — the empty arcade after closing, one cabinet still glowing.
// 
// THE TUNE is title.js's lead note for note (A C E | F A C | E G E | D C · A), its 3-3-2
// sixteenths doubled to eighths, so it sings as a dotted-quarter tresillo behind the beat. THE
// HARMONY is title.js's Am7 · Fmaj7 | Cmaj7 · G, one a bar and coloured:
//   A   | Am11 | F6/9 | Cmaj9 | G9sus4 |
//   B   | Fmaj9 | Dm11 | Em11 | D9 ‖ Fmaj9 | Dm11 | Em11 | G9sus4 |   (the same tune, reharmonised)
// THE GUITAR LOOP (FRPP-6 nylon) is a fingerpicked two-bar "sample" that never changes — a
// quartal E A D G picked up the strings, then an Fadd9 shape with a C–D hammer-on — while the
// bass moves under it (Am11 → C6/9, Fadd9 → G11).
// 
//   1–4    AFTER CLOSING — the nylon loop alone through a closed lowpass (the speaker in the next room), the record crackling; the Rhodes from bar 3, the celesta twinkle; the filter opens into
//   5–12   THE BEAT DROPS — boom-bap at 84, swing 58, lazy snare, late hats, a rim click; the fretless; the Rhodes; the VIBES on the tune, twice
//   13–20  the FLUTE takes the tune; the vibes answer with the twinkle; a shaker, ghost hats, open hats; a fill into
//   21–28  BREAKDOWN — the loop drops out: the tune on the nylon itself, fingerstyle, over the reharmonised changes; the Rhodes held through its tape wobble; kick and rim only under a "tape" lowpass (21–24), the half-time beat back (25–28); the record slows into
//   29–36  THE LAST CHORUS — flute and vibes an octave apart on the tune, the loop back, the Rhodes pushing, the full kit with open hats; at 33 the clean electric doubles the tune an octave under
//   37–40  ONE CABINET STILL GLOWING — the loop and the Rhodes, the celesta twinkle, kick and rim, the lowpass closing — and the beat drops again on bar 5
// 
// Sounds: vibes (mrdrVibraphone) and flute (mrdrConcertFlute) on the tune; the FRPP-6 nylon
// (frppNylon) on the loop and the breakdown's tune, the FRPP-6 clean electric (frppCleanElectric)
// an octave under in the last chorus; the Rhodes (rmndTineEP) through tape wow and a slow chorus;
// the FRPP-6 fretless (Fretless · Upright, song-local: softer, darker, shorter, a 40 ms glide);
// the Breakbeat kit dusted with a bit crusher — kick, lazy snare, ghosts, a rim click, washy hats
// with late ghost 16ths, a shaker; a celesta (tngrCelesta) on title.js's twinkle; vinyl crackle
// and surface noise (song-local). Swing 58; the snare and hats played late by per-bar lane
// offsets. The tape moments are lowpass Spot FX on the master (intro, breakdown, bar 28, outro).

import assert from 'node:assert/strict';
import { installDom } from './dom-stub.js';
installDom();
const {performancePlan, PerformanceTestState, PERFORMANCE_STAGES}=await import('../src/game/performance-test.js');
const {STAGE_BY_ID}=await import('../src/data/stages.js');
const {Dev}=await import('../src/dev/index.js');
const {beginPerformanceCapture,performanceCaptureActive}=await import('../src/engine/performance-capture.js');
for(const id of PERFORMANCE_STAGES){
 const [p]=performancePlan(id);
 assert.ok(STAGE_BY_ID[p.id]);assert.equal(p.seconds,30);assert.deepEqual(p,performancePlan(id)[0]);
}
assert.throws(()=>performancePlan('unknown'));
const s=new PerformanceTestState({onExit(){}});
s.running=true;s.report={results:[]};s.previousDev={enabled:true,timeScale:1};s.showReport=()=>{};
Dev.enabled=false;beginPerformanceCapture();s.finish('stopped');
assert.equal(performanceCaptureActive(),false);assert.equal(Dev.enabled,true);assert.equal(s.report.status,'stopped');
s.finish('ignored');assert.equal(s.report.status,'stopped');
console.log('ok: repeatable valid stages, cancellation restores tools and disarms capture');
const {startCrumbSession,suspendCrumbPersistence,crumb}=await import('../src/engine/diag.js');
let writes=0;const set=localStorage.setItem.bind(localStorage);
localStorage.setItem=(...a)=>{writes++;return set(...a);};
startCrumbSession('performance-test');const before=writes;
suspendCrumbPersistence(true);for(let i=0;i<10;i++)crumb('run',i);
assert.equal(writes,before,'no breadcrumb storage while testing');
suspendCrumbPersistence(false);crumb('after test');assert.equal(writes,before+1,'normal crash persistence resumes');
console.log('ok: benchmark suspends and restores diagnostic writes');
const {newPerformanceSuite,recordSuiteRun,TARGETED_PERFORMANCE_STAGES}=await import('../src/game/performance-test.js');
const {STAGES}=await import('../src/data/stages.js');
const suite=newPerformanceSuite();
assert.deepEqual(suite.stages,STAGES.map(s=>s.id),'every campaign stage included');
assert.equal(suite.qualityMode,'fixed','existing suite defaults to fixed quality');
const autoSuite=newPerformanceSuite(TARGETED_PERFORMANCE_STAGES,null,{qualityMode:'auto'});
assert.deepEqual(autoSuite.stages,['speed-3','frost-3','crypt-3','gravity-3','office-2','surge-3']);
assert.equal(autoSuite.qualityMode,'auto');
assert.equal(autoSuite.densityTarget,null,'Auto mode does not pin a density');
assert.throws(()=>newPerformanceSuite(TARGETED_PERFORMANCE_STAGES,1.5,{qualityMode:'auto'}));
assert.throws(()=>newPerformanceSuite(STAGES.map(s=>s.id),null,{qualityMode:'unknown'}));
recordSuiteRun(suite,{status:'complete',finished:'first',results:[{id:suite.stages[0]}]});
assert.equal(suite.index,1);
recordSuiteRun(suite,{status:'stopped',finished:'second',results:[]});
assert.equal(suite.index,1,'interrupted stage is retried');
assert.equal(suite.runs.length,2,'partial attempts preserved');
const restored=JSON.parse(JSON.stringify(suite));
while(restored.index<restored.stages.length)recordSuiteRun(restored,{status:'complete',results:[]});
assert.equal(restored.status,'complete');
assert.equal(restored.runs.length,STAGES.length+1);
console.log('ok: all stages, persisted progress, interruption/retry, combined report completion');
recordSuiteRun(autoSuite,{status:'complete',finished:'auto-first',results:[]});
assert.equal(autoSuite.qualityMode,'auto','suite mode is retained across saved progress');
console.log('ok: automatic quality mode is explicit, unpinned, and retained');

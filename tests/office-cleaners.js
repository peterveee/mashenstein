import assert from 'node:assert/strict';
import {officeFrame,FACTORS,OFFICE_ZOOM} from '../src/engine/stylePacks/officeClimb.js';
import {OFFICE_CORRIDORS,officeFounderPlan} from '../src/engine/stylePacks/officeLigne/progression.js';
import {officeCleanerPlaces} from '../src/engine/stylePacks/officeLigne/cleanerPlacement.js';
import {officeArtworks} from '../src/engine/stylePacks/officeLigne/artwork.js';
import {totalDistFor} from '../src/game/layout.js';
const total=totalDistFor(210,100,'meetings');
const f=officeFrame('open',0,0,{left:0,right:total},OFFICE_CORRIDORS.open);
f.founderPlan=officeFounderPlan('open',total);
const places=officeCleanerPlaces(f);
assert.deepEqual(places.map(p=>p.kind),['working','hang']);
assert.ok(places[0].x>Math.min(...f.founderPlan.lifts.map(([,end])=>end)));
assert.ok(places[0].x<total*FACTORS.wall*OFFICE_ZOOM*0.2);
assert.ok(places[1].x>places[0].x+480);
assert.ok(officeArtworks(f).some(a=>a.x===places[1].posterX&&a.poster?.label==='HANG IN THERE'));
for(const p of places)assert.ok(!f.founderPlan.avoid.some(([a,b])=>p.x+50>a&&p.x-50<b));
assert.deepEqual(officeCleanerPlaces({...f,camX:1000,wall:{...f.wall,shift:420}}),places);
assert.deepEqual(officeCleanerPlaces({...f,floor:'lobby'}),[]);
assert.deepEqual(officeCleanerPlaces({...f,founderPlan:null}),[]);
console.log('ok: two finite office cleaners, early setup, real adjacent poster and room clearance');

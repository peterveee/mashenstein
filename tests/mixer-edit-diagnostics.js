import assert from 'node:assert/strict';
import { createEditDiagnostics } from '../tools/lib/mixer-edit-diagnostics.js';
let time = 0;
const diag = createEditDiagnostics({ limit: 3, now: () => time });
const receiver = { value: 7, run: diag.wrap('edit', function (duration) { time += duration; return this.value; }) };
for (const ms of [1, 2, 3, 4, 5]) assert.equal(receiver.run(ms), 7);
assert.deepEqual(diag.snapshot().edit, { count: 5, errors: 0, totalMs: 15, maxMs: 5, retained: 3, p50Ms: 4, p95Ms: 4 });
const failure = new Error('test');
assert.throws(diag.wrap('failure', () => { time += 2; throw failure; }), error => error === failure);
assert.equal(diag.snapshot().failure.errors, 1);
const promise = Promise.resolve(9);
assert.equal(diag.wrap('async', () => promise)(), promise, 'promise identity and timing semantics are unchanged');
assert.throws(() => diag.wrap('edit', () => {}), /Duplicate/);
const snapshot = diag.snapshot(); snapshot.edit.count = 100;
assert.equal(diag.snapshot().edit.count, 5, 'exported snapshots cannot mutate counters');
diag.reset(); assert.equal(diag.snapshot().edit.count, 0); assert.equal(diag.snapshot().edit.retained, 0);
const original = () => 123;
const off = createEditDiagnostics({ enabled: false, now: () => { throw Error('disabled clock read'); } });
assert.equal(off.wrap('edit', original), original, 'disabled diagnostics add no wrapper');
assert.deepEqual(off.snapshot(), {});
assert.throws(() => createEditDiagnostics({ limit: Infinity }), RangeError);
console.log('MIXER EDIT DIAGNOSTICS: PASSED');

// Real inspector and generation paths, isolated storage and mocked writes.
import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { mkdirSync } from 'node:fs';
import { generateBanger } from '../tools/lib/banger/index.js';
import { laneFx, posOf } from '../src/data/automation.js';
const { chromium } = createRequire(import.meta.url)('playwright');
const browser = await chromium.launch({ headless: true, args: ['--mute-audio'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } });
const errors = []; page.on('pageerror', e => errors.push(e.message));
let generated, take = 1, posts = [];
const track = () => ({ id: 'section-fx-ui-test', title: 'Section FX UI Test', slug: 'section-fx-ui-test', group: 'banger', writable: true, bank: generated.bank, banger: { ...generated.banger, take } });
const takes = () => ({ take, takes: Array.from({length:take},(_,i)=>i+1), mixed:false, previous:take>1?take-1:null, next:null, banger:track().banger });
await page.route('**/*', async route => {
  const req = route.request(), url = new URL(req.url());
  if (url.pathname === '/diagnostics-log') return route.fulfill({status:200,body:'{}'});
  if (url.pathname === '/banger-takes' && generated) return route.fulfill({json:takes()});
  if (['/make-banger','/banger-take'].includes(url.pathname)) {
    const body = req.postDataJSON(); posts.push(body); generated = body.generated;
    if (body.direction === 'another') take++;
    return route.fulfill({json:{ track:track(), mix:generated.mix, arrangement:generated.arrangement, takes:takes() }});
  }
  if (req.method() !== 'GET') return route.fulfill({status:200,body:'{}'});
  return route.continue();
});
await page.addInitScript(() => {
  if (sessionStorage.getItem('section-fx-test')) return;
  sessionStorage.setItem('section-fx-test','1');
  localStorage.setItem('mash-mixer-tutorial-seen','1');
  localStorage.setItem('mash-mixer-song','plumber');
  localStorage.setItem('mash-mixer-banger-mode','full');
  localStorage.setItem('mash-mixer-banger',JSON.stringify({style:'trance',form:{template:'club'},sectionFx:{mode:'off',firstEffect:'room',firstPart:'hook',firstSection:'intro',firstRange:'first',secondEffect:'pingpong',secondPart:'hook',secondSection:'intro',secondRange:'whole'}}));
});
const openNew = async () => { await page.locator('#navbtn').click(); await page.locator('#makebanger').click(); await page.locator('#bgstrip').waitFor(); };
const change = async (selector,value) => page.locator(selector).evaluate((el,value)=>{el.value=value;el.dispatchEvent(new Event('change',{bubbles:true}));},value);
const commitNumber = async (selector,value) => change(selector,String(value));
const choose = async (i=0) => page.locator('.bgblock').nth(i).click();
const waitPosts = async count => { for(let i=0;i<100&&posts.length<count;i++) await page.waitForTimeout(100); assert.equal(posts.length,count); await page.waitForTimeout(200); };
try {
  await page.goto(process.env.MASH_MIXER_URL || 'http://127.0.0.1:8010/');
  await openNew();
  assert.equal(await page.locator('[data-group="sectionFx"][data-key="firstEffect"]').count(),0);
  await choose();
  assert.equal(await page.locator('[data-fx-row]').count(),2,'legacy rules expand onto matching individual blocks');
  assert.equal(await page.locator('[data-fx-key="presetId"]').first().inputValue(),'generic:room');
  assert.equal(await page.locator('[data-fx-key="presetId"]').nth(1).inputValue(),'generic:pingpong');
  await page.locator('[data-fx-remove]').first().click(); await page.locator('[data-fx-remove]').first().click();
  await page.locator('[data-fx-add]').click();
  await commitNumber('[data-fx-param="wet"]',.41);
  await change('[data-fx-param="division"]','0.75');
  await commitNumber('[data-fx-param="feedback"]',.36);
  assert.equal(await page.locator('#bgformreset').count(),0,'FX alone does not draw the form');
  assert.match(await page.locator('.bgblock').first().innerText(),/FX/);
  await choose(2); assert.equal(await page.locator('[data-fx-row]').count(),0,'other block is independent');
  await choose();
  await change('[data-fx-key="part"]','choir');
  assert.match(await page.locator('.bgsectionfx .bangerwarn').innerText(),/absent or silent/);
  await change('[data-fx-key="part"]','hook');
  mkdirSync('work/mockups/banger-section-effects',{recursive:true});
  await page.screenshot({path:'work/mockups/banger-section-effects/intro-inspector.png',fullPage:true});
  await page.locator('#askok').click(); await waitPosts(1);
  const first = generated, intro = first.form.find(x=>x.type==='intro');
  const row = first.banger.options.sectionFx.assignments[intro.id][0];
  assert.equal(row.chain[0].params.wet,.41); assert.equal(row.chain[0].params.feedback,.36);
  assert.equal(row.chain[0].params.division,.75); assert.equal(first.banger.options.form.sections,null);
  const baseline = generateBanger({riff:first.banger.riff,seed:first.banger.seed, options:{...first.banger.options,sectionFx:{mode:'off'}}});
  assert.deepEqual(first.bank,baseline.bank); assert.deepEqual(first.mix,baseline.mix);
  assert.ok(laneFx(first.arrangement.automation,first.banger.laneOf.hook).some(s=>s.from===posOf(intro.from,0)&&s.chain.some(e=>e.id==='pingpong')));
  await page.locator('#bangerreport').click();
  assert.match(await page.locator('#askbody').innerText(),/Section choice/);
  assert.match(await page.locator('#askbody').innerText(),/0.41/);
  await page.locator('#askok').click();
  await page.locator('#navbtn').click();
  await page.locator('#bangersettings').click(); await choose();
  assert.equal(await page.locator('[data-fx-param="wet"]').inputValue(),'0.41','recipe reopens with copied settings');
  await page.locator('#bgfsmore').click(); await commitNumber('#bgfslabel','Echo Intro');
  await page.locator('.bgblock.on').press('Alt+ArrowRight');
  assert.equal(await page.locator('[data-fx-param="wet"]').inputValue(),'0.41','assignment follows moved/renamed/resized block');
  await page.locator('#askok').click(); await waitPosts(2);
  assert.equal(generated.banger.options.sectionFx.assignments[intro.id][0].chain[0].params.wet,.41);
  await page.locator('#navbtn').click(); await page.locator('#bangermodify').click();
  await choose(1);
  assert.equal(await page.locator('#bgfstype').isDisabled(),true);
  assert.equal(await page.locator('#bgfsmore').isDisabled(),true);
  assert.equal(await page.locator('#bgfsdel').isDisabled(),true);
  assert.equal(await page.locator('[data-fx-param="wet"]').isEnabled(),true);
  const orderBefore = await page.locator('.bgblocklab').allTextContents();
  await page.locator('.bgblock.on').press('Alt+ArrowRight');
  assert.deepEqual(await page.locator('.bgblocklab').allTextContents(),orderBefore);
  await choose(1); await commitNumber('[data-fx-param="wet"]',.3);
  await page.locator('#askok').click(); await waitPosts(3);
  assert.equal(posts[2].direction,'modify');
  assert.deepEqual(generated.bank,posts[1].generated.bank,'FX modification retains the notes');
  await page.locator('#navbtn').click(); await page.locator('#bangeragain').click(); await waitPosts(4);
  assert.equal(generated.banger.options.sectionFx.assignments[intro.id][0].chain[0].params.wet,.3,'Another Take retains explicit settings');
  await page.locator('#navbtn').click(); await page.locator('#bangersettings').click(); await choose(1);
  await page.locator('#bgformreset').click(); await choose();
  assert.equal(await page.locator('[data-fx-row]').count(),0,'form reset clears explicit assignments');
  await page.locator('[data-fx-add]').click();
  await page.locator('#bgtemplate button[data-template="pop"]').click(); await choose();
  assert.equal(await page.locator('[data-fx-row]').count(),0,'template switch clears assignments');
  await page.locator('[data-fx-add]').click(); await page.locator('#bgdefaults').click(); await choose();
  assert.equal(await page.locator('[data-fx-row]').count(),0,'Style Defaults clears assignments');
  await page.locator('#askcancel').click();
  assert.deepEqual(errors,[]);
  console.log('SECTION FX UI: passed (actual inspector, generation, report, recipe, move/resize, Modify locks and resets)');
} finally { await browser.close(); }

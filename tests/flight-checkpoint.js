import assert from 'node:assert/strict';
import { beginFlightCheckpoint, readFlightCheckpoint, saveFlightMidpoint, finishFlightCheckpoint } from '../src/game/flight/checkpoint.js';
const save = { slot: {campaign:{bossesDown:{}}}, persist(){this.disk=JSON.stringify(this.slot);} };
const result={success:true,stage:{id:'rhythm-3'},finalHero:'b33p',time:70,damageTaken:2,coins:11};
const p=beginFlightCheckpoint(save,result,123);
assert.equal(readFlightCheckpoint(save.slot),p);
assert.equal(save.slot.campaign.bossesDown.rhythm,undefined);
assert.equal(readFlightCheckpoint(save.slot,'neon-3'),null);
saveFlightMidpoint(save,p,20,1);
const reloaded={...save,slot:JSON.parse(save.disk)};
const recovered=readFlightCheckpoint(reloaded.slot);
assert.equal(recovered.checkpoint,1);assert.equal(recovered.seed,123);
let payouts=0;
const apply=(s,r)=>{payouts++;s.slot.coins=(s.slot.coins||0)+r.coins;s.persist();return {coins:r.coins};};
const settled=finishFlightCheckpoint(reloaded,recovered,apply,44,3);
assert.equal(settled.result.time,114);assert.equal(settled.result.damageTaken,5);
assert.equal(reloaded.slot.campaign.bossesDown.rhythm,true);
assert.equal(readFlightCheckpoint(reloaded.slot),null);
assert.equal(finishFlightCheckpoint(reloaded,recovered,apply,44,3),null);
assert.equal(payouts,1);assert.equal(JSON.parse(reloaded.disk).campaign.pendingFlight,undefined);
const bad={campaign:{pendingFlight:{...p,checkpoint:2}}};assert.equal(readFlightCheckpoint(bad),null);
console.log('Flight checkpoint: durable midpoint, deferred rewards, legacy-safe missing field, one-time completion passed.');
